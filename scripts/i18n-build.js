/**
 * Builds src/i18n/strings.generated.js from the numbered translation files (src/i18n/tr-*.txt, lines "id¦it¦fr¦de")
 * and the English texts they number (src/i18n/source-en.json). Run after editing a tr file:  node scripts/i18n-build.js
 */
const fs = require('fs');
const path = require('path');

const dir = path.join(__dirname, '..', 'src', 'i18n');
const source = JSON.parse(fs.readFileSync(path.join(dir, 'source-en.json'), 'utf8'));
const fixes = { 171: ['frequenti'], 224: ['Sulle nostre', 'À propos de nos', 'Fragen zu unseren'] };
const rows = [];
let missing = 0;
for (const f of fs.readdirSync(dir).filter((x) => /^tr-.*\.txt$/.test(x)).sort()) {
  for (const line of fs.readFileSync(path.join(dir, f), 'utf8').split('\n')) {
    if (!line.trim()) continue;
    const [id, it, fr, de] = line.split('¦').map((s) => s.trim());
    const en = source[Number(id)];
    if (!en) { console.log('no English text for id', id); continue; }
    let row = [en.t, it, fr, de];
    if (fixes[id]) row = [en.t, fixes[id][0] || it, fixes[id][1] || fr, fixes[id][2] || de];
    rows.push(row);
  }
}
const ids = new Set(rows.map((r) => r[0]));
source.forEach((s) => { if (!ids.has(s.t)) missing += 1; });
fs.writeFileSync(path.join(dir, 'strings.generated.js'), `// Generated by scripts/i18n-build.js from tr-*.txt. Do not edit by hand.\nmodule.exports = ${JSON.stringify(rows)};\n`);
console.log(`${rows.length} rows written, ${missing} English texts still without a translation`);
